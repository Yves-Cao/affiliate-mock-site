const check = (condition,message) => { assert.ok(condition,message); assertions += 1; };
const call = async (operation,params = {},context = operations) => (await service.request(operation,params,context)).data;
const detail = async (ticket_id,context = operations) => call("detail",{ticket_id},context);
async function write(operation,ticket_id,payload = {},context = operations) {
  const {ticket} = await detail(ticket_id,context);
  return call(operation,{ticket_id,version:ticket.version,idempotency_key:`test-${++sequence}`,...payload},context);
}
async function rejected(promise,code,reason) {
  await assert.rejects(promise,error => {
    check(error.code === code,`expected ${code}; received ${error.code}: ${error.message}`);
    if (reason) check(error.details.reason_code === reason,`expected reason ${reason}`);
    check(Boolean(error.trace_id),"error has trace");
    return true;
  });
}
